// Prints the documentation graph as one navigable page.
//
// `docs:status` answers "what is open?". This answers the question that costs
// more when nobody can answer it: "what governs this, and what did it replace?"
// Both read the registry only — the map opens a document just to read the title
// of a claim someone superseded, which is the one fact the registry stores as
// an identifier rather than as prose.
//
// The output is deliberately mostly links. A map that restates its documents
// becomes a second place to keep them correct, which is how two of them start
// disagreeing.
//
// Run with `task docs:map`.

import { readFile } from 'node:fs/promises';
import { join } from 'node:path';

import {
  inboundOf,
  isChangeTarget,
  loadArtifacts,
  parseClaims,
  relationsOf,
  splitTarget,
} from './docs-registry.mjs';

const { artifacts } = await loadArtifacts();
const entries = Object.entries(artifacts).filter(([, e]) => e && typeof e === 'object');
const of = (kind) => entries.filter(([, e]) => e.kind === kind);
const live = ([, e]) => e.state !== 'superseded' && e.state !== 'closed';
const link = (id) => {
  const path = artifacts[id]?.path;
  return path ? `[${id}](docs/${path})` : id;
};
const out = (id, type) => relationsOf(artifacts[id]).filter((r) => r.type === type).map((r) => r.target);

console.log('# Coquena — documentation map\n');
console.log('Generated by `task docs:map`. Every name links to the document that owns it.\n');

// ---------------------------------------------------------------- the spine
console.log('## Start here\n');
for (const [id, entry] of of('story')) console.log(`- **story** ${link(id)} — ${entry.title}`);
for (const [id, entry] of of('usecase')) console.log(`- **usecase** ${link(id)} — ${entry.title}`);
console.log();

// ------------------------------------------------------------- what governs
const decisions = of('decision').filter(live);
if (decisions.length > 0) {
  console.log('## In force\n');
  console.log('A decision binds until something supersedes it. Read these before proposing.\n');
  for (const [id, entry] of decisions) {
    console.log(`- ${link(id)} — ${entry.title}`);
    const consumers = inboundOf(artifacts, id).filter((r) => r.type === 'motivated-by');
    if (consumers.length > 0)
      console.log(`  - governs ${consumers.map((r) => link(r.source)).join(', ')}`);
  }
  console.log();
}

// ------------------------------------------------- what stopped being true
const superseded = [];
for (const [id] of entries)
  for (const target of out(id, 'supersedes')) {
    if (isChangeTarget(target)) continue;
    const { artifact, claim } = splitTarget(target);
    superseded.push({ by: id, artifact, claim });
  }

if (superseded.length > 0) {
  console.log('## Superseded\n');
  console.log(
    'The expensive failure this repository has had is a replaced conclusion being\n' +
      'read as current. Each claim below carries a marker in its own document, which\n' +
      '`docs:validate` enforces — this list is the same fact, gathered.\n',
  );
  for (const { by, artifact, claim } of superseded) {
    let title = '';
    if (claim != null) {
      const path = artifacts[artifact]?.path;
      if (path) {
        try {
          const found = parseClaims(await readFile(join('docs', path), 'utf8')).find((c) => c.id === claim);
          if (found) title = ` — ${found.title}`;
        } catch {
          /* an unreadable document is reported by docs:validate, not here */
        }
      }
    }
    console.log(`- ${link(artifact)}${claim ? `#${claim}` : ''}${title}`);
    console.log(`  - replaced by ${link(by)}`);
  }
  console.log();
}

// ------------------------------------------------------------------ evidence
const findings = of('finding')
  .filter(live)
  .map(([id, entry]) => [id, entry, inboundOf(artifacts, id).length])
  .sort((a, b) => b[2] - a[2]);
if (findings.length > 0) {
  console.log('## Evidence\n');
  console.log('Facts about the world, most depended-upon first. A finding survives the change.\n');
  for (const [id, entry, refs] of findings)
    console.log(`- ${link(id)} (${refs} ref) — ${entry.title}`);
  console.log();
}

// ----------------------------------------------------------------- open work
const rank = (e) => (e.priority === 'high' ? 0 : e.priority === 'normal' ? 1 : 2) + (e.state === 'blocked' ? 4 : 0);
const open = of('backlog')
  .filter(([, e]) => e.state === 'open' || e.state === 'blocked')
  .sort(([a, x], [b, y]) => rank(x) - rank(y) || a.localeCompare(b));
if (open.length > 0) {
  console.log('## Open\n');
  for (const [id, entry] of open) {
    const blockers = out(id, 'blocked-by');
    const why = out(id, 'motivated-by').map((t) => link(splitTarget(t).artifact));
    const tail = blockers.length > 0 ? ` — blocked by ${blockers.join(', ')}` : '';
    console.log(`- \`${entry.priority ?? '?'}\` ${link(id)}${tail}`);
    if (why.length > 0) console.log(`  - from ${why.join(', ')}`);
  }
  console.log();
}

const closed = entries.filter(([, e]) => e.state === 'closed').length;
console.log(`---\n\n${entries.length} artifacts, ${closed} closed. Open RFCs: ${of('rfc').filter(([, e]) => e.state === 'open').length}.`);
